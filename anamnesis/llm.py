"""Chat-model provider abstraction.

``openai`` uses native tool calling. ``ollama`` targets a local model through the
OpenAI-compatible endpoint that Ollama exposes, so the same code path serves both.
``offline`` has no model at all — the agent falls back to a deterministic router,
and the API says so explicitly in every response.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from . import config


@dataclass
class ToolCall:
    id: str
    name: str
    arguments: dict[str, Any] = field(default_factory=dict)


@dataclass
class ChatResponse:
    content: str = ""
    tool_calls: list[ToolCall] = field(default_factory=list)


class LLMUnavailable(RuntimeError):
    """Raised when a provider is selected but cannot be reached or configured."""


def active_provider() -> str:
    provider = config.LLM_PROVIDER.lower()
    if provider == "openai" and not config.OPENAI_API_KEY:
        return "offline"
    return provider


def describe_provider() -> dict[str, object]:
    provider = active_provider()
    if provider == "openai":
        return {
            "provider": "openai",
            "model": config.OPENAI_CHAT_MODEL,
            "generative": True,
            "note": "Answers are generated by an LLM constrained to retrieved context.",
        }
    if provider == "ollama":
        return {
            "provider": "ollama",
            "model": config.OLLAMA_CHAT_MODEL,
            "generative": True,
            "note": f"Local model served by Ollama at {config.OLLAMA_HOST}.",
        }
    return {
        "provider": "offline",
        "model": "deterministic-router",
        "generative": False,
        "note": (
            "No language model is running. A keyword router selects one tool and the "
            "answer is assembled from templates over the tool's output. Behaviour is "
            "fully deterministic; it is not LLM reasoning."
        ),
    }


def _client(provider: str):
    from openai import OpenAI  # imported lazily: not needed in offline mode

    if provider == "ollama":
        return OpenAI(base_url=f"{config.OLLAMA_HOST}/v1", api_key="ollama")
    if not config.OPENAI_API_KEY:
        raise LLMUnavailable("OPENAI_API_KEY is not set")
    return OpenAI(api_key=config.OPENAI_API_KEY)


def chat(
    messages: list[dict[str, Any]],
    tools: list[dict[str, Any]] | None = None,
    provider: str | None = None,
) -> ChatResponse:
    """One turn against the configured provider, with optional tool calling."""
    import json

    provider = (provider or active_provider()).lower()
    if provider == "offline":
        raise LLMUnavailable("No chat provider configured (running in offline mode)")

    model = config.OLLAMA_CHAT_MODEL if provider == "ollama" else config.OPENAI_CHAT_MODEL
    kwargs: dict[str, Any] = {"model": model, "messages": messages, "temperature": 0}
    if tools:
        kwargs["tools"] = tools
        kwargs["tool_choice"] = "auto"

    try:
        completion = _client(provider).chat.completions.create(**kwargs)
    except LLMUnavailable:
        raise
    except Exception as exc:  # network, auth, model-not-found, rate limit
        raise LLMUnavailable(f"{provider} request failed: {exc}") from exc

    message = completion.choices[0].message
    calls = []
    for call in getattr(message, "tool_calls", None) or []:
        try:
            arguments = json.loads(call.function.arguments or "{}")
        except json.JSONDecodeError:
            arguments = {}
        calls.append(ToolCall(id=call.id, name=call.function.name, arguments=arguments))
    return ChatResponse(content=message.content or "", tool_calls=calls)
